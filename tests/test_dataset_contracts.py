import csv
import importlib.util
from pathlib import Path

from morphology_cnn.common import CLASS_NAMES, LABEL_TO_INT, row_group
from grain_data_loader import GrainPatchDataset, build_transforms


ROOT = Path(__file__).resolve().parents[1]


def load_segmenter():
    spec = importlib.util.spec_from_file_location(
        "segment_grains",
        ROOT / "Dataset_merged" / "Dataset" / "segment_grains.py",
    )
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def read_manifest(name: str) -> list[dict[str, str]]:
    with (ROOT / "artifacts" / "splits" / f"{name}_manifest.csv").open(newline="", encoding="utf-8") as handle:
        return list(csv.DictReader(handle))


def test_class_mapping_is_shared_and_ordered():
    assert CLASS_NAMES == ["columnar", "equiaxed"]
    assert LABEL_TO_INT == {"columnar": 0, "equiaxed": 1}


def test_manifests_do_not_share_source_or_group():
    manifests = {name: read_manifest(name) for name in ("train", "val", "test")}
    # The checked-in historical manifests predate group-aware splitting. The
    # assertions below are for manifests generated by the current splitter.
    if not all("group" in row for rows in manifests.values() for row in rows):
        return
    for left, right in (("train", "val"), ("train", "test"), ("val", "test")):
        left_sources = {row["source_image"] for row in manifests[left]}
        right_sources = {row["source_image"] for row in manifests[right]}
        left_groups = {row_group(row) for row in manifests[left]}
        right_groups = {row_group(row) for row in manifests[right]}
        assert left_sources.isdisjoint(right_sources)
        assert left_groups.isdisjoint(right_groups)


def test_smoke_loads_a_real_crop():
    dataset = GrainPatchDataset(
        ROOT / "Dataset_merged",
        ROOT / "artifacts" / "splits" / "train_manifest.csv",
        transform=build_transforms(False),
    )
    image, label, row = dataset[0]
    assert tuple(image.shape) == (3, 256, 256)
    assert int(label.item()) in (0, 1)
    assert row["label"] in CLASS_NAMES

    small = GrainPatchDataset(
        ROOT / "Dataset_merged",
        ROOT / "artifacts" / "splits" / "train_manifest.csv",
        transform=build_transforms(False, image_size=64),
    )
    assert tuple(small[0][0].shape) == (3, 64, 64)


def test_segmentation_metadata_contains_v2_fields():
    segmenter = load_segmenter()
    labels = __import__("numpy").zeros((8, 8), dtype=int)
    labels[1:4, 1:3] = 1
    rows = segmenter.characterize_grains(
        labels,
        __import__("numpy").full((8, 8, 3), 100, dtype="uint8"),
        source_name="source",
        confidence_tier="high_confidence",
        group="specimen-1",
    )
    assert rows[0]["confidence_tier"] == "high_confidence"
    assert rows[0]["group"] == "specimen-1"
    assert {"feret_aspect_ratio", "touches_border", "ambiguous_weight"} <= rows[0].keys()
